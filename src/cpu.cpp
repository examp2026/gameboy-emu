#include "cpu.h"

//------------------------------------------------------------------------------

void CPU::setA(uint8_t value)
{
    A = value;
}

//------------------------------------------------------------------------------

void CPU::setB(uint8_t value)
{
    B = value;
}

//------------------------------------------------------------------------------

void CPU::setC(uint8_t value)
{
    C = value;
}

//------------------------------------------------------------------------------

void CPU::setBC(uint16_t value)
{
    setB(static_cast<uint8_t>(value >> 8));
    setC(static_cast<uint8_t>(value & 0x00FF));
}

//------------------------------------------------------------------------------

void CPU::setD(uint8_t value)
{
    D = value;
}

//------------------------------------------------------------------------------

void CPU::setE(uint8_t value)
{
    E = value;
}

//------------------------------------------------------------------------------

void CPU::setDE(uint16_t value)
{
    setD(static_cast<uint8_t>(value >> 8));
    setE(static_cast<uint8_t>(value & 0x00FF));
}

//------------------------------------------------------------------------------

void CPU::setH(uint8_t value)
{
    H = value;
}

//------------------------------------------------------------------------------

void CPU::setL(uint8_t value)
{
    L = value;
}

//------------------------------------------------------------------------------

void CPU::setHL(uint16_t value)
{
    setH(static_cast<uint8_t>(value >> 8));
    setL(static_cast<uint8_t>(value & 0x00FF));
}

//------------------------------------------------------------------------------

void CPU::setF(uint8_t value)
{
    F = value & 0xF0;
}

//------------------------------------------------------------------------------

void CPU::setAF(uint16_t value)
{
    setA(static_cast<uint8_t>(value >> 8));
    setF(static_cast<uint8_t>(value));
}

//------------------------------------------------------------------------------

void CPU::setSP(uint16_t pointer)
{
    SP = pointer;
}

//------------------------------------------------------------------------------

void CPU::setPC(uint16_t pointer)
{
    PC = pointer;
}

//------------------------------------------------------------------------------

uint16_t CPU::getA() const
{
    return A;
}

//------------------------------------------------------------------------------

uint16_t CPU::getB() const
{
    return B;
}

//------------------------------------------------------------------------------

uint16_t CPU::getC() const
{
    return C;
}

//------------------------------------------------------------------------------

uint16_t CPU::getD() const
{
    return D;
}

//------------------------------------------------------------------------------

uint16_t CPU::getE() const
{
    return E;
}

//------------------------------------------------------------------------------

uint16_t CPU::getH() const
{
    return H;
}

//------------------------------------------------------------------------------

uint16_t CPU::getL() const
{
    return L;
}

//------------------------------------------------------------------------------

uint16_t CPU::getF() const
{
    return F;
}

//------------------------------------------------------------------------------

uint16_t CPU::getBC() const
{
    uint16_t register_pair = (B << 8) | C;
    return register_pair;
}

//------------------------------------------------------------------------------

uint16_t CPU::getDE() const
{
    uint16_t register_pair = (D << 8) | E;
    return register_pair;
}

//------------------------------------------------------------------------------

uint16_t CPU::getHL() const
{
    uint16_t register_pair = (H << 8) | L;
    return register_pair;
}

//------------------------------------------------------------------------------

uint16_t CPU::getAF() const
{
    uint16_t register_pair = (A << 8) | F;
    return register_pair;
}

//------------------------------------------------------------------------------

uint16_t CPU::getSP() const
{
    return SP;
}

//------------------------------------------------------------------------------

uint16_t CPU::getPC() const
{
    return PC;
}
